"""One-shot generator for config/site_contour.yaml (grid receptors at 40.0 m AGL).

Kept in the repo so the grid can be regenerated with different extents/spacings
without hand-editing 700 yaml entries. The generated yaml is the artefact that
run_contour.py reads; re-running this script overwrites it.
"""
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from solar_glare.analysis import load_config  # noqa: E402
from solar_glare.geometry import enu_to_latlon  # noqa: E402

SRC = os.path.join(ROOT, "config", "site.yaml")
DST = os.path.join(ROOT, "config", "site_contour.yaml")
TMP = os.path.join(ROOT, "scripts", "_tmp_grid.yaml")

# Bounding box that covers BOTH glare footprints (az098 hits east of the array,
# az278 hits west), measured by running the real pipeline on a 2 km probe grid.
LAT0, LAT1, LON0, LON1 = 12.57, 12.73, 100.94, 101.27
STEP_M = 300.0
# Grid receptor height above ground level (m). 0 = ground level, 40 = elevated (e.g. driver eye height)
GRID_HEIGHT_AGL_M = 40.0

# The easternmost DROP_EAST_COLS columns of that box are DISCARDED. Every
# committed case faces WEST (az278), so the glare footprint -- and therefore
# every RG1-3 zone -- lies WEST of the array; the eastern third of the box came
# back uniformly RG0 and only cost run time. This is a pure truncation: each
# retained point keeps exactly the coordinate it had in the full grid, because
# the origin and the cell pitch are still taken from the FULL box above.
DROP_EAST_COLS = 30

# The `cases:` block is copied from site.yaml, which enables all seven design
# cases. Only the three committed west-facing contour cases are run; the other
# four are written back COMMENTED OUT (not deleted) so one edit re-enables them.
KEEP_CASES = {"az278_e903_t15"}

# Hour range for contour analysis (inclusive hours 0-23). Used by run_contour.py.
HOUR_RANGE = [6, 18]

HEADER = """# GENERATED by scripts/_gen_contour_config.py -- edit that script, not this file.
#
# Same site / environment / arrays / cases as config/site.yaml (copied verbatim,
# so the physics is IDENTICAL), except for `receptors`, which is a regular
# ~1 km ENU-aligned grid at height_agl_m: %.1f instead of the 65
# real 40 m route / terminal / observation points. The point of that grid is to
# give run_contour.py enough spatial samples to draw an isorisk-style contour
# map of the IEC 62471 risk zones. The easternmost columns of the original
# bounding box are dropped (see DROP_EAST_COLS): all committed cases face west,
# so every RG1-3 zone lies west of the array and the east side stayed RG0.
#
# The 65 original receptors are ALSO kept below (renamed v_<name>) at their
# original 40 m AGL. They are the validation set: run_contour.py compares their
# rows against the committed output/<label>/results/summary.csv and fails if
# anything moved, which is what proves the contour run uses the same method.
""" % GRID_HEIGHT_AGL_M

GRID_COMMENT = """
receptors:
  # ---------------------------------------------------------------------
  # (1) contour grid: ~%d m spacing, height_agl_m = %.1f.
  #     Name = g_<row>_<col>, row = north, col = east, both 0-based.
  #     %d x %d = %d points, ordered north-to-south then west-to-east, which is
  #     the order contour.py reshapes the summary table back into a 2-D field.
  # ---------------------------------------------------------------------
"""

VAL_COMMENT = """
  # ---------------------------------------------------------------------
  # (2) validation set: the 65 receptors of config/site.yaml verbatim
  #     (40 m AGL), renamed with a v_ prefix. Not used for the contours --
  #     run_contour.py only grids the g_* entries -- but their summary rows
  #     must reproduce the committed output/<label>/results/summary.csv.
  # ---------------------------------------------------------------------
"""


def main():
    cfg = load_config(SRC)
    ref = cfg["site"]["reference"]

    def ll2xy(lat, lon):
        x = (lon - ref["lon"]) * 111320.0 * math.cos(math.radians(ref["lat"]))
        y = (lat - ref["lat"]) * 110574.0
        return x, y

    xs, ys = [], []
    for la in (LAT0, LAT1):
        for lo in (LON0, LON1):
            x, y = ll2xy(la, lo)
            xs.append(x)
            ys.append(y)
    x0, y0 = min(xs), min(ys)
    nx = int(round((max(xs) - x0) / STEP_M))
    ny = int(round((max(ys) - y0) / STEP_M))
    step_x = (max(xs) - x0) / nx
    step_y = (max(ys) - y0) / ny
    step = (step_x + step_y) / 2.0

    ncol = (nx + 1) - DROP_EAST_COLS
    if ncol < 2:
        raise SystemExit("DROP_EAST_COLS leaves fewer than 2 columns")

    grid = []
    for j in range(ny + 1):
        y = y0 + j * step_y
        for i in range(ncol):
            x = x0 + i * step_x
            la, lo = enu_to_latlon(ref["lat"], ref["lon"], x, y)
            grid.append(
                '  - name: "g_%02d_%02d"\n'
                "    lat: %.14f\n"
                "    lon: %.14f\n"
                "    height_agl_m: %.1f" % (j, i, la, lo, GRID_HEIGHT_AGL_M)
            )

    val = []
    for r in cfg["receptors"]:
        val.append(
            '  - name: "v_%s"\n'
            "    lat: %.14f\n"
            "    lon: %.14f\n"
            "    height_agl_m: %.1f"
            % (r["name"], r["lat"], r["lon"], float(r["height_agl_m"]))
        )

    npts = len(grid)
    body = (
        HEADER
        + (GRID_COMMENT % (step, GRID_HEIGHT_AGL_M, ny + 1, ncol, npts))
        + "\n".join(grid)
        + "\n"
        + VAL_COMMENT
        + "\n".join(val)
        + "\n"
    )

    # Keep everything above `receptors:` byte-identical to site.yaml, except the
    # `cases:` block: site.yaml carries all seven design cases, and a contour
    # sweep over all of them would nearly double the ~1 h runtime while adding
    # no committed result. Cases outside KEEP_CASES are emitted COMMENTED OUT
    # rather than deleted, so they stay one edit away from being re-enabled.
    # Also inject contour-specific `hour_range` into the site section.
    src_text = open(SRC, encoding="utf-8").read()
    head = src_text[: src_text.index("\nreceptors:")].rstrip() + "\n"
    kept, dropped, lines = [], [], []
    for line in head.split("\n"):
        m = re.match(r'^(\s*)- \{ label: "([^"]+)"', line)
        if m and m.group(2) not in KEEP_CASES:
            line = m.group(1) + "# " + line[len(m.group(1)):]
            dropped.append(m.group(2))
        elif m:
            kept.append(m.group(2))
        lines.append(line)
    # Inject hour_range after linke_turbidity line
    for i, line in enumerate(lines):
        if "linke_turbidity:" in line:
            lines.insert(i + 1, f"  hour_range: {HOUR_RANGE}")
            break
    head = "\n".join(lines)
    missing = KEEP_CASES - set(kept)
    if missing:
        raise SystemExit("KEEP_CASES not present in site.yaml: %s"
                         % ", ".join(sorted(missing)))
    out = head + "\n" + body
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    os.remove(TMP) if os.path.exists(TMP) else None
    print("wrote %s" % DST)
    print("  grid %d x %d = %d points at %.1f m, height_agl_m %.1f"
          " (dropped %d east columns of the %d x %d box)"
          % (ny + 1, ncol, npts, step, GRID_HEIGHT_AGL_M, DROP_EAST_COLS, ny + 1, nx + 1))
    print("  validation receptors: %d" % len(val))
    print("  cases active: %s | commented out: %s"
          % (", ".join(kept), ", ".join(dropped)))


if __name__ == "__main__":
    main()